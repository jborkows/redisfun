package redis;

import org.junit.jupiter.api.MethodOrderer;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestInfo;
import org.junit.jupiter.api.TestMethodOrder;

import java.io.IOException;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

@TestMethodOrder(MethodOrderer.Random.class)
class RedisServerXaddCommandIntegrationTest {
    private static final String NOT_VALID_KEY = "-ERR The ID specified in XADD is equal or smaller than the target stream top item";

    @Test
    void createKey(TestInfo testInfo) throws IOException {
        var key = SharedRedisServer.key(testInfo);
        var response = SharedRedisServer.run("XADD stream_key 1-1 key value key2 value2".replaceAll("stream_key", key));
        assertEquals(List.of("$" + "1-1".length(), "1-1"), response);
    }

    @Test
    void noStreamKeyResultsInError() throws IOException {
        var response = SharedRedisServer.run("XADD");
        assertEquals(List.of("-ERR wrong number of arguments for 'XADD' command"), response);
    }

    @Test
    void cannotAdd00(TestInfo testInfo) throws IOException {
        var key = SharedRedisServer.key(testInfo);
        var response = SharedRedisServer.run("XADD %s 0-0 foo bar".formatted(key));
        assertEquals(List.of("-ERR The ID specified in XADD must be greater than 0-0"), response);
    }

    @Test
    void cannotAddWhenMillisecondPartIsSmaller(TestInfo testInfo) throws IOException {
        var key = SharedRedisServer.key(testInfo);
        SharedRedisServer.run("XADD %s 1-1 foo bar".formatted(key));
        var response = SharedRedisServer.run("XADD %s 0-1 foo bar".formatted(key));
        assertEquals(List.of(NOT_VALID_KEY), response);
    }

    @Test
    void cannotAddWhenSequenceNumberIsSmaller(TestInfo testInfo) throws IOException {
        var key = SharedRedisServer.key(testInfo);
        SharedRedisServer.run("XADD %s 1-2 foo bar".formatted(key));
        var response = SharedRedisServer.run("XADD %s 1-1 foo bar".formatted(key));
        assertEquals(List.of(NOT_VALID_KEY), response);
    }

    @Test
    void cannotAddWhenEntryIdIsDuplicated(TestInfo testInfo) throws IOException {
        var key = SharedRedisServer.key(testInfo);
        SharedRedisServer.run("XADD %s 1-1 foo bar".formatted(key));
        var response = SharedRedisServer.run("XADD %s 1-1 foo bar".formatted(key));
        assertEquals(List.of(NOT_VALID_KEY), response);
    }

    @Test
    void canAddInOrderSequenceNumber(TestInfo testInfo) throws IOException {
        var key = SharedRedisServer.key(testInfo);
        SharedRedisServer.run("XADD %s 1-1 foo bar".formatted(key));
        var response = SharedRedisServer.run("XADD %s 1-2 foo bar".formatted(key));
        assertEquals(List.of("$" + "1-2".length(), "1-2"), response);
    }

    @Test
    void canAddInOrderMilliseconds(TestInfo testInfo) throws IOException {
        var key = SharedRedisServer.key(testInfo);
        SharedRedisServer.run("XADD %s 1-1 foo bar".formatted(key));
        var response = SharedRedisServer.run("XADD %s 2-1 foo bar".formatted(key));
        assertEquals(List.of("$" + "2-1".length(), "2-1"), response);
    }

    @Test
    void canAddAutogenerated(TestInfo testInfo) throws IOException {
        var key = SharedRedisServer.key(testInfo);
        SharedRedisServer.run("XADD %s 1-1 foo bar".formatted(key));
        var response = SharedRedisServer.run("XADD %s * foo bar".formatted(key));
        assertNotEquals(List.of(NOT_VALID_KEY), response);
        assertEquals(2, response.size());
        assertFalse(response.getFirst().startsWith("-ERR"));
        assertFalse(response.get(1).startsWith("-ERR"));
    }

    @Test
    void partiallyGeneratedIdWhenEmpty(TestInfo testInfo) throws IOException {
        var key = SharedRedisServer.key(testInfo);
        var response = SharedRedisServer.run("XADD %s 1-* foo bar".formatted(key));
        assertEquals(List.of("$" + "1-0".length(), "1-0"), response);
    }

    @Test
    void partiallyGeneratedIdWhenAlreadyExists(TestInfo testInfo) throws IOException {
        var key = SharedRedisServer.key(testInfo);
        SharedRedisServer.run("XADD %s 1-5 foo bar".formatted(key));
        var response = SharedRedisServer.run("XADD %s 1-* foo bar".formatted(key));
        assertEquals(List.of("$" + "1-6".length(), "1-6"), response);
    }

    @Test
    void partiallyGeneratedIdWhenAlreadyExistsForZero(TestInfo testInfo) throws IOException {
        var key = SharedRedisServer.key(testInfo);
        SharedRedisServer.run("XADD %s 0-* foo bar".formatted(key));
        var response = SharedRedisServer.run("XADD %s 0-* foo bar".formatted(key));
        assertEquals(List.of("$" + "0-2".length(), "0-2"), response);
    }

    @Test
    void partiallyGeneratedWithSkip(TestInfo testInfo) throws IOException {
        var key = SharedRedisServer.key(testInfo);
        SharedRedisServer.run("XADD %s 0-* foo bar".formatted(key));
        var response = SharedRedisServer.run("XADD %s 1-* foo bar".formatted(key));
        assertEquals(List.of("$" + "1-0".length(), "1-0"), response);
    }
}
